"""
Load test for the Online Bookstore (SRS BOOK-NF-001 and BOOK-NF-004).

Simulates many shoppers at once browsing the catalog, searching, and opening book pages,
then reports response times per page and checks the target: 90% of requests in 2 seconds
or less. It uses only the Python standard library, so there is nothing to install.

Start the site first, then run for example:
    py tests/perf/load_test.py --users 50 --seconds 30

Each run is appended to tests/perf/results.md so it can be used in the Test Summary Report.
"""
import argparse
import json
import threading
import time
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime
from pathlib import Path

TARGET_SECONDS = 2.0  # BOOK-NF-001: 90% of requests at or under this


def fetch(url):
    """One request. Returns (status code, seconds taken). Status 0 means no answer."""
    started = time.perf_counter()
    try:
        with urllib.request.urlopen(url, timeout=30) as response:
            response.read()
            status = response.status
    except urllib.error.HTTPError as error:
        status = error.code
    except Exception:
        status = 0
    return status, time.perf_counter() - started


def percentile(sorted_values, fraction):
    if not sorted_values:
        return 0.0
    return sorted_values[int(fraction * (len(sorted_values) - 1))]


def main():
    parser = argparse.ArgumentParser(description="Load test for the Online Bookstore")
    parser.add_argument("--host", default="http://localhost:8000")
    parser.add_argument("--users", type=int, default=50, help="simulated users at the same time")
    parser.add_argument("--seconds", type=int, default=30, help="how long to run")
    args = parser.parse_args()

    first_page = json.load(urllib.request.urlopen(f"{args.host}/api/books/", timeout=30))
    if not first_page["results"]:
        raise SystemExit("The catalog is empty. Run: python manage.py seed_books")
    book_id = first_page["results"][0]["id"]

    pages = [
        ("catalog list", "/api/books/?sort=title"),
        ("search", "/api/books/?q=orwell"),
        ("filter and sort", "/api/books/?genre=Fantasy&sort=price_asc"),
        ("home page", "/"),
        ("book detail page", f"/books/{book_id}/"),
        ("book reviews", f"/api/books/{book_id}/reviews/"),
    ]
    timings = {name: [] for name, _ in pages}
    failures = {name: 0 for name, _ in pages}
    lock = threading.Lock()
    stop_at = time.time() + args.seconds

    def virtual_user(index):
        step = index  # users start on different pages so the load is mixed
        while time.time() < stop_at:
            name, path = pages[step % len(pages)]
            step += 1
            status, seconds = fetch(args.host + path)
            with lock:
                timings[name].append(seconds)
                if status != 200:
                    failures[name] += 1
            time.sleep(0.1)

    print(f"Running {args.users} users for {args.seconds}s against {args.host} ...")
    started = time.time()
    with ThreadPoolExecutor(max_workers=args.users) as pool:
        list(pool.map(virtual_user, range(args.users)))
    elapsed = time.time() - started

    lines = [
        "| Page | Requests | Errors | Median (ms) | 90th pct (ms) | 95th pct (ms) | Slowest (ms) |",
        "|---|---|---|---|---|---|---|",
    ]
    everything = []
    for name, _ in pages:
        values = sorted(timings[name])
        everything.extend(values)
        lines.append(
            f"| {name} | {len(values)} | {failures[name]} | {percentile(values, 0.5) * 1000:.0f} | "
            f"{percentile(values, 0.9) * 1000:.0f} | {percentile(values, 0.95) * 1000:.0f} | "
            f"{(values[-1] * 1000 if values else 0):.0f} |"
        )

    everything.sort()
    total = len(everything)
    errors = sum(failures.values())
    p90 = percentile(everything, 0.9)
    verdict = "PASS" if total and p90 <= TARGET_SECONDS and errors == 0 else "FAIL"
    summary = (
        f"{total} requests in {elapsed:.0f}s ({total / elapsed:.1f} requests/second), "
        f"{errors} errors. Overall 90th percentile: {p90 * 1000:.0f} ms "
        f"(target {TARGET_SECONDS * 1000:.0f} ms). Result: {verdict}"
    )

    report = (
        f"\n### {datetime.now():%Y-%m-%d %H:%M} - {args.users} users for {args.seconds}s\n\n"
        + "\n".join(lines)
        + f"\n\n{summary}\n"
    )
    print(report)

    results_file = Path(__file__).with_name("results.md")
    if not results_file.exists():
        results_file.write_text("# Load test results\n\nGenerated by `tests/perf/load_test.py`.\n")
    with results_file.open("a", encoding="utf-8") as handle:
        handle.write(report)
    print(f"Saved to {results_file}")


if __name__ == "__main__":
    main()